import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const require = createRequire(new URL('../frontend/package.json', import.meta.url));
const ts = require('typescript');
const source = readFileSync(new URL('../ui/src/i18n/labels.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText;
const context = { exports: {} };
vm.runInNewContext(js, context);
const registry = Object.fromEntries(
  Object.entries(context.exports.DEFAULT_LABELS).map(([key, values]) => [
    key,
    {
      section: key.split('.')[0],
      description: `Interface text: ${key}`,
      placeholders: [
        ...new Set(
          JSON.stringify(values.en)
            .matchAll(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)
            .map((m) => m[1]),
        ),
      ].sort(),
      values,
    },
  ]),
);
const path = new URL('../backend/internal/siteconfig/labels.json', import.meta.url);
const body = JSON.stringify(registry, null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== body) {
    throw Error('Label registry is stale');
  }
} else {
  writeFileSync(path, body);
}
console.log('Label registry synchronized.');

const localePacks = JSON.parse(
  readFileSync(new URL('../backend/internal/locale/packs.json', import.meta.url), 'utf8'),
);
const localeText =
  '// Generated by scripts/build-label-registry.mjs.\nexport const LOCALES = [\n' +
  localePacks
    .map(
      ({ code, name, dir, intl, defaultVisible, interfaceOrder }) =>
        "  { code: '" +
        code +
        "', name: '" +
        name +
        "', dir: '" +
        dir +
        "', intl: '" +
        intl +
        "', defaultVisible: " +
        defaultVisible +
        ', interfaceOrder: ' +
        interfaceOrder +
        ' },',
    )
    .join('\n') +
  '\n] as const;\n';
const localePath = new URL('../ui/src/i18n/locales.generated.ts', import.meta.url);
const prettier = require('prettier');
const localeFile = fileURLToPath(localePath);
const localeSource = await prettier.format(localeText, {
  ...(await prettier.resolveConfig(localeFile)),
  filepath: localeFile,
});
if (process.argv.includes('--check')) {
  if (readFileSync(localePath, 'utf8') !== localeSource) {
    throw Error('Locale registry is stale');
  }
} else {
  writeFileSync(localePath, localeSource);
}
